IF OBJECT_ID(N'dbo.AGG_ORQ_CARD01_FOTO', N'U') IS NULL
BEGIN
  SELECT DTA_MOVIMENTO,LOTE_ID,DTH_CARGA,NUM_AGENCIA,NUM_MATRICULA,DTH_VENDA,NOM_PRODUTO,
         AREA_PRODUTO,COD_PLANO,STA_SITUACAO,STA_ASSINATURA,STA_PAGO,
         COUNT_BIG(*) QTD_REGISTROS, CONVERT(bigint,COUNT(DISTINCT COD_PROPOSTA)) QTD_PROPOSTAS_DISTINTAS,
         CONVERT(bigint,COUNT(DISTINCT COD_VENDA)) QTD_VENDAS_DISTINTAS, SUM(VLR_PREMIO) VLR_PREMIO_TOTAL,
         COUNT_BIG(VLR_PREMIO) QTD_PREMIOS_INFORMADOS
    INTO dbo.AGG_ORQ_CARD01_FOTO FROM dbo.FAT_ORQ_CARD01_FOTO
   GROUP BY DTA_MOVIMENTO,LOTE_ID,DTH_CARGA,NUM_AGENCIA,NUM_MATRICULA,DTH_VENDA,NOM_PRODUTO,
            AREA_PRODUTO,COD_PLANO,STA_SITUACAO,STA_ASSINATURA,STA_PAGO;
END
ELSE
  INSERT dbo.AGG_ORQ_CARD01_FOTO
